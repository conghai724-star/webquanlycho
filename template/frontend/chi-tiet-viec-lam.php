<script>
(function(){
  var current = 0;
  var timer = null;
  var delay = 5000;

  function getVisibleCount(){
    if(window.innerWidth <= 560) return 1;
    if(window.innerWidth <= 1024) return 2;
    return 3;
  }

  function getMaxSlide(){
    var track = document.getElementById('jdFeaturedTrack');
    if(!track) return 0;
    var cards = track.querySelectorAll('.jd-feature-card');
    return Math.max(cards.length - getVisibleCount(), 0);
  }

  function renderDots(){
    var dotsWrap = document.getElementById('jdFeaturedDots');
    if(!dotsWrap) return;

    var max = getMaxSlide();
    var html = '';
    for(var i = 0; i <= max; i++){
      html += '<button type="button" class="jd-slider-dot '+(i === current ? 'active' : '')+'" onclick="jdFeaturedGo('+i+')"></button>';
    }
    dotsWrap.innerHTML = html;
  }

  function updateSlider(){
    var track = document.getElementById('jdFeaturedTrack');
    if(!track) return;

    var cards = track.querySelectorAll('.jd-feature-card');
    if(!cards.length) return;

    var max = getMaxSlide();
    if(current > max) current = 0;
    if(current < 0) current = max;

    var gap = 14;
    var cardWidth = cards[0].offsetWidth + gap;
    track.style.transition = 'transform .45s ease';
    track.style.transform = 'translateX(-' + (current * cardWidth) + 'px)';

    renderDots();
  }

  function resetAuto(){
    clearInterval(timer);
    timer = setInterval(function(){
      current++;
      if(current > getMaxSlide()) current = 0;
      updateSlider();
    }, delay);
  }

  window.jdFeaturedSlide = function(direction){
    current += direction;
    updateSlider();
    resetAuto();
  };

  window.jdFeaturedGo = function(index){
    current = index;
    updateSlider();
    resetAuto();
  };

  window.addEventListener('resize', function(){
    current = 0;
    updateSlider();
    resetAuto();
  });

  document.addEventListener('DOMContentLoaded', function(){
    updateSlider();
    resetAuto();
  });
})();
</script>

