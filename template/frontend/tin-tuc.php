// Category tabs filter
(function(){
  var tabs = document.querySelectorAll('.news-tab');
  tabs.forEach(function(tab){
    tab.addEventListener('click',function(){
      tabs.forEach(function(t){t.classList.remove('active')});
      tab.classList.add('active');
      var sec = tab.getAttribute('data-section');
      var sections = {
        all:[document.getElementById('sec-site'),document.getElementById('sec-employer'),document.getElementById('sec-seeker')],
        site:[document.getElementById('sec-site')],
        employer:[document.getElementById('sec-employer')],
        seeker:[document.getElementById('sec-seeker')]
      };
      ['sec-site','sec-employer','sec-seeker'].forEach(function(id){
        var el = document.getElementById(id);
        el.style.display='none';
      });
      var toShow = sections[sec]||sections.all;
      toShow.forEach(function(el){if(el)el.style.display='block'});
    });
  });
})();


// Load more news: each click adds 2 more rows in the clicked section.
(function(){
  function getGridColumns(grid){
    var columns = window.getComputedStyle(grid).gridTemplateColumns;
    if (!columns || columns === 'none') return 1;
    return columns.split(' ').filter(Boolean).length || 1;
  }

  function markClonedItem(item, index){
    var clone = item.cloneNode(true);
    clone.classList.add('loaded-more-item');
    clone.querySelectorAll('[id]').forEach(function(node){ node.removeAttribute('id'); });
    var title = clone.querySelector('.card-title, .li-title');
    if (title) title.textContent = title.textContent.replace(/\s*\(\d+\)$/,'') + ' (' + index + ')';
    return clone;
  }

  document.querySelectorAll('.btn-load-more').forEach(function(button){
    button.dataset.loadRound = '0';
    button.addEventListener('click', function(){
      var section = button.closest('.news-section');
      if (!section) return;

      var grid = section.querySelector('.posts-grid');
      var list = section.querySelector('.posts-list');
      var container = grid || list;
      if (!container) return;

      var sourceItems = Array.prototype.slice.call(container.children).filter(function(item){
        return item.classList.contains('post-card') || item.classList.contains('post-list-item');
      });
      if (!sourceItems.length) return;

      var round = parseInt(button.dataset.loadRound || '0', 10) + 1;
      button.dataset.loadRound = String(round);

      var perRow = grid ? getGridColumns(grid) : 1;
      var amount = perRow * 2;
      var fragment = document.createDocumentFragment();
      for (var i = 0; i < amount; i++) {
        var source = sourceItems[i % sourceItems.length];
        fragment.appendChild(markClonedItem(source, round + '-' + (i + 1)));
      }
      container.appendChild(fragment);
    });
  });
})();
// Hot slider
(function(){
  var track = document.getElementById('hotSliderTrack');
  var dotsWrap = document.getElementById('hotSliderDots');
  var slides = document.querySelectorAll('.hot-slide');
  var current = 0;
  var perView = 4;
  var autoTimer;

  function getPerView(){
    var w = window.innerWidth;
    if(w<=640) return 1;
    if(w<=900) return 2;
    return 3;
  }

  function totalGroups(){return Math.ceil(slides.length / getPerView())}

  function buildDots(){
    dotsWrap.innerHTML='';
    for(var i=0;i<totalGroups();i++){
      var dot = document.createElement('button');
      dot.type='button';
      dot.className='hs-dot'+(i===0?' active':'');
      dot.setAttribute('aria-label','Trang '+(i+1));
      (function(idx){dot.addEventListener('click',function(){goTo(idx)})})(i);
      dotsWrap.appendChild(dot);
    }
  }

  function goTo(page){
    perView = getPerView();
    var max = totalGroups()-1;
    if(page<0)page=max;
    if(page>max)page=0;
    current=page;
    var pct = (100/slides.length)*perView*current;
    track.style.transform='translateX(-'+pct+'%)';
    document.querySelectorAll('.hs-dot').forEach(function(d,i){d.classList.toggle('active',i===current)});
    resetAuto();
  }

  function resetAuto(){
    clearInterval(autoTimer);
    autoTimer=setInterval(function(){goTo(current+1)},4000);
  }

  document.getElementById('sliderNext').addEventListener('click',function(){goTo(current+1)});
  document.getElementById('sliderPrev').addEventListener('click',function(){goTo(current-1)});

  // Touch support
  var tx=0;
  document.getElementById('hotSliderWrap').addEventListener('touchstart',function(e){tx=e.changedTouches[0].clientX},{passive:true});
  document.getElementById('hotSliderWrap').addEventListener('touchend',function(e){
    var diff=tx-e.changedTouches[0].clientX;
    if(Math.abs(diff)>40) goTo(current+(diff>0?1:-1));
  },{passive:true});

  window.addEventListener('resize',function(){buildDots();goTo(0)});
  buildDots();
  resetAuto();
})();
