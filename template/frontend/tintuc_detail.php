<script>
// Reading progress bar
window.addEventListener('scroll',function(){
  var body=document.body;
  var html=document.documentElement;
  var scrollTop=window.scrollY;
  var total=Math.max(body.scrollHeight,html.scrollHeight)-window.innerHeight;
  var pct=total>0?(scrollTop/total)*100:0;
  document.getElementById('readProgress').style.width=pct+'%';
});

// Floating share bar: show after scrolling 300px
window.addEventListener('scroll',function(){
  var fs=document.getElementById('floatingShare');
  if(fs)fs.style.opacity=window.scrollY>300?'1':'0';
});

// Skill demand bars animate on load
window.addEventListener('load',function(){
  document.querySelectorAll('.skill-demand-fill').forEach(function(bar){
    var w=bar.style.width;
    bar.style.width='0';
    setTimeout(function(){bar.style.width=w},300);
  });
});

// Reactions toggle
function toggleReaction(btn){
  var isActive=btn.classList.contains('active');
  document.querySelectorAll('.reaction-btn').forEach(function(b){b.classList.remove('active')});
  if(!isActive) btn.classList.add('active');
}

// TOC highlight on scroll
(function(){
  var headings=document.querySelectorAll('.article-body h2[id]');
  var tocLinks=document.querySelectorAll('.toc-link');
  window.addEventListener('scroll',function(){
    var scrollY=window.scrollY+120;
    var current='';
    headings.forEach(function(h){if(h.offsetTop<=scrollY)current=h.id});
    tocLinks.forEach(function(link){
      var href=link.getAttribute('href').replace('#','');
      link.classList.toggle('active',href===current);
    });
  });
})();

// Hot Slider
(function(){
  var track=document.getElementById('hsTrack');
  var dotsWrap=document.getElementById('hsDots');
  var slides=document.querySelectorAll('.hs-slide');
  var current=0;
  var autoTimer;

  function perView(){
    var w=window.innerWidth;
    if(w<=480)return 1;
    if(w<=640)return 1;
    if(w<=900)return 2;
    if(w<=1060)return 3;
    return 4;
  }
  function groups(){return Math.ceil(slides.length/perView())}

  function buildDots(){
    dotsWrap.innerHTML='';
    for(var i=0;i<groups();i++){
      var d=document.createElement('div');
      d.className='hs-dot'+(i===0?' active':'');
      (function(idx){d.addEventListener('click',function(){go(idx)})})(i);
      dotsWrap.appendChild(d);
    }
  }

  function go(page){
    var g=groups();
    if(page<0)page=g-1;
    if(page>=g)page=0;
    current=page;
    var pct=(100/slides.length)*perView()*current;
    track.style.transform='translateX(-'+pct+'%)';
    document.querySelectorAll('.hs-dot').forEach(function(d,i){d.classList.toggle('active',i===current)});
    clearInterval(autoTimer);
    autoTimer=setInterval(function(){go(current+1)},4000);
  }

  document.getElementById('hsNext').addEventListener('click',function(){go(current+1)});
  document.getElementById('hsPrev').addEventListener('click',function(){go(current-1)});

  var tx=0;
  document.getElementById('hsWrap').addEventListener('touchstart',function(e){tx=e.changedTouches[0].clientX},{passive:true});
  document.getElementById('hsWrap').addEventListener('touchend',function(e){
    var d=tx-e.changedTouches[0].clientX;
    if(Math.abs(d)>40)go(current+(d>0?1:-1));
  },{passive:true});

  window.addEventListener('resize',function(){buildDots();go(0)});
  buildDots();
  autoTimer=setInterval(function(){go(current+1)},4000);
})();
</script>

